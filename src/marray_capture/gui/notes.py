def params_html() -> str:
    """「参数说明」小窗的内容。"""
    out = []
    group = None
    for _, grp, name, desc in PARAMS:
        if grp != group:
            group = grp
            out.append(f"<h3 style='margin:16px 0 6px 0;'>{grp}</h3>")
        out.append(
            f"<p style='margin:0 0 10px 0; line-height:155%;'>"
            f"<b>{name}</b><br>{desc}</p>")
    return "".join(out)


def params_markdown() -> str:
    """docs/protocol-params.md 的内容。与界面同源, 不会漂移。"""
    import re

    def plain(s: str) -> str:
        return re.sub(r"<[^>]+>", "", s).replace("&gt;", ">").replace("&lt;", "<")

    lines = ["# 采集参数说明", "",
             "> 本文件由 `uv run marray-capture --dump-params` 生成，"
             "与界面「方案」页的「参数说明」按钮同源。改动请改 "
             "`src/marray_capture/gui/notes.py` 的 `PARAMS`。", ""]
    group = None
    for _, grp, name, desc in PARAMS:
        if grp != group:
            group = grp
            lines += [f"## {grp}", ""]
        lines += [f"### {name}", "", plain(desc), ""]
    return "\n".join(lines)


